#!/usr/bin/env bash
# generate_tool_instructions.sh — the ONE generator for the keyword/critical-rules
# block every non-Claude tool's instruction file carries (GitHub Copilot's
# .github/copilot-instructions.md, Codex's AGENTS.md — Antigravity's GEMINI.md is
# intentionally NOT wired in here, see note below). CLAUDE.md is the single
# source of truth; this script extracts the CRITICAL RULES list and the core
# keyword table from it and splices them into each target between generated-
# block markers, leaving every tool-specific section (identity, wrap-up banner,
# logging) untouched.
#
# WHY (2026-10-03): foh (and the rest of the fleet) had a CLAUDE.md but no
# .github/copilot-instructions.md and an AGENTS.md with no keyword table, so
# VS Code chat (Copilot, incl. local Ollama models) knew none of the fleet's
# keywords. Two swarm tasks both wanted to build "the generator" (this one;
# swarm-66401322 child task-204a7798 for GEMINI.md/AGENTS.md) — to keep it to
# ONE, this script only registers copilot-instructions.md + AGENTS.md's keyword
# section. Add GEMINI.md to TARGETS (and give it GEN:KEYWORDS markers) once
# that task's own generator work lands, instead of writing a second one.
#
# SOURCE (V1 gate G1, 2026-10-22): a target under templates/ — what ships in the
# npm package — always renders from the generic templates/CRITICAL_RULES.md, so
# no operator rule or lane reaches a fresh install. Any other target renders
# from the repo's CLAUDE.md, falling back to the generic file when there is no
# CLAUDE.md (a fresh install has none). GEN_TOOL_INSTRUCTIONS_SOURCE overrides.
#
# Markers (each optional per-target — a file only needs the pairs it uses):
#   <!-- GEN:RULES:BEGIN -->   ... <!-- GEN:RULES:END -->      9 CRITICAL RULES
#   <!-- GEN:BOOT:BEGIN -->    ... <!-- GEN:BOOT:END -->       boot/BOOT_REPORT note
#   <!-- GEN:KEYWORDS:BEGIN --> ... <!-- GEN:KEYWORDS:END -->  core keyword table
#
# Usage:
#   scripts/generate_tool_instructions.sh                 regen both registered master-repo targets
#   scripts/generate_tool_instructions.sh --check          exit 1 if any registered target is stale (CI use)
#   scripts/generate_tool_instructions.sh --dry-run        report only, no write
#   scripts/generate_tool_instructions.sh <file> [--init <template>] [--dry-run]
#                                           regen one target; --init copies <template> first
#                                           if <file> does not exist yet (fleet rollout use)
# Exit 0 on success / nothing stale; 1 if --check found drift or a write failed.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
GENERIC_SOURCE="$ROOT/templates/CRITICAL_RULES.md"
SOURCE="" SOURCE_LABEL="" RULES_BODY="" KEYWORDS_TABLE=""

# ── extract from the source (CLAUDE.md or the generic shipped rules) ─────────
extract_section() { # <start-heading-regex> <file>
  awk -v start="$1" 'BEGIN{p=0} $0 ~ start {p=1; next} p && /^---$/{exit} p{print}' "$2"
}

# source_for <target-file> → the file its RULES/KEYWORDS blocks render from.
source_for() {
  if [ -n "${GEN_TOOL_INSTRUCTIONS_SOURCE:-}" ]; then echo "$GEN_TOOL_INSTRUCTIONS_SOURCE"; return; fi
  case "$1" in "$ROOT"/templates/*) echo "$GENERIC_SOURCE"; return ;; esac
  if [ -f "$ROOT/CLAUDE.md" ]; then echo "$ROOT/CLAUDE.md"; else echo "$GENERIC_SOURCE"; fi
}

# load_source <file> — set SOURCE, SOURCE_LABEL, RULES_BODY, KEYWORDS_TABLE.
load_source() {
  SOURCE="$1"
  [ -f "$SOURCE" ] || { echo "generate_tool_instructions: source not found: $SOURCE" >&2; exit 1; }
  case "$SOURCE" in "$ROOT"/*) SOURCE_LABEL="${SOURCE#"$ROOT"/}" ;; *) SOURCE_LABEL="$(basename "$SOURCE")" ;; esac
  RULES_BODY="$(extract_section '^## CRITICAL RULES' "$SOURCE")"
  KEYWORDS_TABLE="$(awk '/^## Quick Keywords — Core/{f=1} f && /^\|/{print} f && /^---$/{exit}' "$SOURCE")"
  [ -n "$RULES_BODY" ]     || { echo "generate_tool_instructions: could not extract CRITICAL RULES from $SOURCE" >&2; exit 1; }
  [ -n "$KEYWORDS_TABLE" ] || { echo "generate_tool_instructions: could not extract the core keyword table from $SOURCE" >&2; exit 1; }
}

rules_block() {
  printf '<!-- GEN:RULES:BEGIN — generated by scripts/generate_tool_instructions.sh from %s §CRITICAL RULES, do not hand-edit between these markers -->\n' "$SOURCE_LABEL"
  printf '## CRITICAL RULES (read before doing anything)\n\n'
  printf '%s\n' "$RULES_BODY"
  printf '<!-- GEN:RULES:END -->\n'
}

boot_block() {
  printf '<!-- GEN:BOOT:BEGIN — generated by scripts/generate_tool_instructions.sh, do not hand-edit between these markers -->\n'
  cat <<'EOF'
## `boot` — read before assuming session state

An interactive session reads `AI/state/boot/BOOT_REPORT.<hostname -s>.md` (master repo path) for this host's last verdict — it never runs `morning_boot.sh` itself. No report yet for this host → say so; don't run the checks yourself.
EOF
  printf '<!-- GEN:BOOT:END -->\n'
}

# short_keywords_table — mechanically trims each row's "What it does" cell to
# its first clause (period/em-dash/arrow, capped at 100 chars). Small local
# models (qwen3-coder, gpt-oss) read this; CLAUDE.md's full cells run several
# sentences each, which is fine for Claude/Codex but defeats a short-instruction
# model. The keyword NAMES still come verbatim from CLAUDE.md's table — only
# the prose length is trimmed, so there's still exactly one inventory of which
# keywords exist.
short_keywords_table() {
  # Split each row on only its FIRST "|" (separating the keyword column from
  # the description column) — several description cells contain literal "|"
  # inside backticks (e.g. the yolo row's `god|<min>|stop`), so a naive
  # split("|") on every pipe shreds those rows.
  printf '%s\n' "$KEYWORDS_TABLE" | /usr/bin/python3 -c '
import sys
for line in sys.stdin:
    line = line.rstrip("\n")
    if not line.startswith("|") or "|" not in line[1:]:
        print(line); continue
    col1, rest = line[1:].split("|", 1)
    rest = rest.rstrip()
    rest_content = rest[:-1] if rest.endswith("|") else rest
    desc = rest_content.strip()
    if set(desc) <= {"-", ":", " ", ""}:
        print(line); continue   # header separator row
    cut = len(desc)
    for delim in [". ", " — ", " → "]:
        i = desc.find(delim)
        if 0 < i < cut:
            cut = i
    cut = min(cut, 90)
    short = desc[:cut].rstrip(" .,—(`*")
    if len(short) < len(desc.rstrip(".")):
        short += "…"
    print("|" + col1 + "| " + short + " |")
'
}

# doc_prefix <target-file> — "AI/documentation/" for a normal fleet repo (the
# framework lives under its AI/ folder there); bare "documentation/" for THIS
# master repo, which dogfoods itself from repo-root docs/ — its AI/ tree is a
# partial mirror that does NOT carry CORE_KEYWORDS.md/KEYWORDS_REFERENCE.md, so
# an AI/-prefixed link here would 404. Decided by what actually exists next to
# the target, not by guessing which repo this is.
doc_prefix() {
  # Target is either <repo>/AGENTS.md or <repo>/.github/copilot-instructions.md
  # — try the file's own directory, then one level up, for the repo root.
  local d repo_root=""
  for d in "$(dirname "$1")" "$(dirname "$(dirname "$1")")"; do
    [ -d "$d/documentation" ] || [ -d "$d/AI" ] || continue
    repo_root="$(cd "$d" && pwd)"; break
  done
  [ -n "$repo_root" ] || repo_root="$(cd "$(dirname "$1")" && pwd)"
  if [ -f "$repo_root/documentation/CORE_KEYWORDS.md" ] && [ ! -f "$repo_root/AI/documentation/CORE_KEYWORDS.md" ]; then
    echo ""
  else
    echo "AI/"
  fi
}

keywords_block() {
  local prefix="${1-AI/}"
  printf '<!-- GEN:KEYWORDS:BEGIN — generated by scripts/generate_tool_instructions.sh from %s §Quick Keywords — Core, do not hand-edit between these markers -->\n' "$SOURCE_LABEL"
  printf '## Quick Keywords\n\n'
  # shellcheck disable=SC2016  # backticks are literal markdown, not expansions
  printf 'Full step-numbered protocol for each: `%sdocumentation/CORE_KEYWORDS.md` (core) / `%sdocumentation/KEYWORDS_REFERENCE.md` (extended, incl. `schedule`, `swarm`, `brain *`, `remote`, `tell`). Announce steps → report per-step result → summary table on every keyword, same protocol Claude follows.\n\n' "$prefix" "$prefix"
  printf '%s\n' "$KEYWORDS_TABLE"
  printf '<!-- GEN:KEYWORDS:END -->\n'
}

keywords_block_short() {
  local prefix="${1-AI/}"
  printf '<!-- GEN:KEYWORDS:BEGIN — generated by scripts/generate_tool_instructions.sh from %s §Quick Keywords — Core (short form), do not hand-edit between these markers -->\n' "$SOURCE_LABEL"
  printf '## Quick Keywords\n\n'
  # shellcheck disable=SC2016  # backticks are literal markdown, not expansions
  printf 'Full protocol for each: `%sdocumentation/CORE_KEYWORDS.md` (core) / `%sdocumentation/KEYWORDS_REFERENCE.md` (extended). Announce steps, report each, end with a summary table.\n\n' "$prefix" "$prefix"
  short_keywords_table
  printf '<!-- GEN:KEYWORDS:END -->\n'
}

# splice_one <file> <marker-name> <block-file> → replace the BEGIN..END marker
# lines (inclusive) with the fresh block (which carries its own BEGIN/END).
# Line-number based (head/tail), not awk -v with a multi-line string — BSD awk
# (macOS) mangles -v values containing embedded newlines into an empty file.
# Returns: 0 if the marker pair was found (and spliced), 1 if absent (no-op).
splice_one() {
  local file="$1" name="$2" blockfile="$3" begin_line end_line tmp
  begin_line="$(grep -n "GEN:${name}:BEGIN" "$file" 2>/dev/null | head -1 | cut -d: -f1)"
  [ -n "$begin_line" ] || return 1
  end_line="$(grep -n "GEN:${name}:END" "$file" 2>/dev/null | head -1 | cut -d: -f1)"
  [ -n "$end_line" ] || return 1
  tmp="$(mktemp)"
  { [ "$begin_line" -gt 1 ] && head -n "$((begin_line - 1))" "$file"; cat "$blockfile"; tail -n "+$((end_line + 1))" "$file"; } > "$tmp"
  mv "$tmp" "$file"
  return 0
}

# regen_target <file> [short] — splice every marker pair present in <file>.
# "short" renders the condensed keyword table (copilot-instructions.md target —
# small local models); omitted/anything else renders the full CLAUDE.md table
# (AGENTS.md — Codex-class models). Prints "changed"/"unchanged"; writes only
# when something actually differs.
regen_target() {
  local file="$1" mode="${2:-full}" prefix before after rules_f boot_f kw_f
  [ -f "$file" ] || { echo "missing"; return 1; }
  prefix="$(doc_prefix "$file")"
  before="$(cat "$file")"
  rules_f="$(mktemp)"; rules_block > "$rules_f"
  boot_f="$(mktemp)"; boot_block > "$boot_f"
  kw_f="$(mktemp)"
  if [ "$mode" = short ]; then keywords_block_short "$prefix" > "$kw_f"; else keywords_block "$prefix" > "$kw_f"; fi
  splice_one "$file" RULES    "$rules_f" || true
  splice_one "$file" BOOT     "$boot_f"  || true
  splice_one "$file" KEYWORDS "$kw_f"    || true
  rm -f "$rules_f" "$boot_f" "$kw_f"
  after="$(cat "$file")"
  if [ "$before" = "$after" ]; then echo "unchanged"; else echo "changed"; fi
}

# bootstrap_markers <file> <mode> — a fleet repo's existing AGENTS.md/copilot
# file predates this generator and carries NO GEN:* markers at all (foh's
# AGENTS.md, 2026-09-21: has headings, no keyword table). splice_one is a
# no-op on a file with no markers, so the very first rollout run would report
# "unchanged" while injecting nothing. Append whichever block(s) this mode
# needs, once — every later run then finds the markers and splices in place.
# "short" (copilot-style) files get RULES+BOOT+KEYWORDS; "full" (AGENTS.md)
# gets only KEYWORDS — AGENTS.md keeps its own hand-maintained CRITICAL RULES.
bootstrap_markers() {
  local file="$1" mode="$2" prefix appended=0
  prefix="$(doc_prefix "$file")"
  if ! grep -q "GEN:KEYWORDS:BEGIN" "$file" 2>/dev/null; then
    { echo; if [ "$mode" = short ]; then keywords_block_short "$prefix"; else keywords_block "$prefix"; fi; } >> "$file"
    appended=1
  fi
  if [ "$mode" = short ]; then
    if ! grep -q "GEN:RULES:BEGIN" "$file" 2>/dev/null; then { echo; rules_block; } >> "$file"; appended=1; fi
    if ! grep -q "GEN:BOOT:BEGIN" "$file" 2>/dev/null; then { echo; boot_block; } >> "$file"; appended=1; fi
  fi
  [ "$appended" = 1 ]
}

# ── CLI ──────────────────────────────────────────────────────────────────────
DRY=0 CHECK=0 TARGET="" INIT="" MODE_OVERRIDE=""
while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1 ;;
    --check)   CHECK=1 ;;
    --init)    shift; INIT="${1:?--init needs a template path}" ;;
    --short)   MODE_OVERRIDE=short ;;
    --full)    MODE_OVERRIDE=full ;;
    -h|--help) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "generate_tool_instructions: unknown flag: $1" >&2; exit 2 ;;
    *) TARGET="$1" ;;
  esac
  shift
done

# copilot-instructions.md always renders the condensed table (small local
# models via VS Code); everything else (AGENTS.md, a fleet repo's AGENTS.md)
# gets the full CLAUDE.md table. --short/--full override for ad-hoc targets.
mode_for() {
  [ -n "$MODE_OVERRIDE" ] && { echo "$MODE_OVERRIDE"; return; }
  case "$1" in *copilot-instructions.md) echo short ;; *) echo full ;; esac
}

REGISTERED=("$ROOT/.github/copilot-instructions.md" "$ROOT/AGENTS.md")

run_one() {
  local file="$1" tmp mode before after
  mode="$(mode_for "$file")"
  case "$file" in /*) ;; *) file="$(pwd)/$file" ;; esac
  load_source "$(source_for "$file")"
  if [ ! -f "$file" ]; then
    if [ -z "$INIT" ]; then
      echo "generate_tool_instructions: $file does not exist (pass --init <template> to bootstrap it)" >&2
      return 1
    fi
    if [ "$DRY" = 1 ] || [ "$CHECK" = 1 ]; then
      echo "WOULD-CREATE  $file  (from $INIT)"
      [ "$CHECK" = 1 ] && return 1
      return 0
    fi
    mkdir -p "$(dirname "$file")"
    cp "$INIT" "$file"
  fi

  if [ "$DRY" = 1 ] || [ "$CHECK" = 1 ]; then
    before="$(cat "$file")"
    # tmp copy lives NEXT TO the original (not /tmp) — doc_prefix looks for
    # sibling documentation/ or AI/ dirs, which only exist relative to the
    # real repo; an unrelated /tmp path made every dry-run mis-detect "AI/"
    # and falsely report WOULD-CHANGE on an already-correct master-repo file.
    tmp="$(dirname "$file")/.generate_tool_instructions.dryrun.$$"
    cp "$file" "$tmp"
    bootstrap_markers "$tmp" "$mode" || true
    regen_target "$tmp" "$mode" >/dev/null
    after="$(cat "$tmp")"
    rm -f "$tmp"
    if [ "$before" = "$after" ]; then
      echo "current  $file"
    else
      echo "WOULD-CHANGE  $file"
      [ "$CHECK" = 1 ] && return 1
    fi
    return 0
  fi

  before="$(cat "$file")"
  bootstrap_markers "$file" "$mode" || true
  regen_target "$file" "$mode" >/dev/null
  after="$(cat "$file")"
  if [ "$before" = "$after" ]; then echo "unchanged  $file"; else echo "changed  $file"; fi
  return 0
}

rc=0
if [ -n "$TARGET" ]; then
  run_one "$TARGET" || rc=1
else
  for f in "${REGISTERED[@]}"; do
    run_one "$f" || rc=1
  done
fi
exit $rc
